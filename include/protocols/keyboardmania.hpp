static_assert(sizeof(keyboardmania_report_descriptor) == 150, "KeyboardMania descriptor is 150 bytes, like the real one");

// The first byte is six always set buttons, then four bytes of seven buttons each and an
// unused bit, then a 2 bit X / Y pointer the controller never moves.
constexpr uint8_t KEYBOARDMANIA_HEADER = 0x3f;
struct KeyboardManiaInputReport {
    uint8_t header;
    uint32_t buttons;
    uint8_t pointer;
    uint8_t reserved[2];
} __attribute__((packed));
static_assert(sizeof(KeyboardManiaInputReport) == 8, "KeyboardMania input is eight bytes");

// Bit in KeyboardManiaInputReport::buttons for each KeyboardManiaButtonType, the 24 keys run
// C1 to B2 and skip the top bit of every byte, which select, start and the wheel fill in.
constexpr uint8_t keyboardmania_bits[] = {
    0, 1, 2, 3, 4, 5, 6,
    8, 9, 10, 11, 12, 13,
    16, 17, 18, 19, 20, 21,
    24, 25, 26, 27, 28,
    // Start, Select, Wheel Up, Wheel Down
    22, 14, 29, 30};
